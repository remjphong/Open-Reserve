import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'

const source = readFileSync('contracts/src/IReserveVault.sol', 'utf8')
const doc = readFileSync('docs/contract-interface.md', 'utf8').split('```solidity\n')[1].split('```')[0]
const normalize = s => s.replace(/\s+/g, '')
assert.equal(normalize(source), normalize(doc), 'Frozen interface document/source drift')
// Forge recompiles the authoritative source; never trust an unchecked stale artifact.
const abi = JSON.parse(execFileSync(process.env.FORGE ?? 'forge', ['inspect', 'IReserveVault', 'abi', '--json'], { cwd: 'contracts', encoding: 'utf8' }))
const content = '// Generated by npm run sdk:generate; do not edit.\n' +
  `export const interfaceSha256 = '${createHash('sha256').update(source).digest('hex')}' as const\n` +
  `export const reserveVaultAbi = ${JSON.stringify(abi, null, 2)} as const\n`
const target = 'packages/contracts-sdk/src/abi.ts'
if (process.argv.includes('--check')) assert.equal(readFileSync(target, 'utf8'), content, 'SDK ABI drift: regenerate and review')
else writeFileSync(target, content)
console.log(`SDK ABI ${process.argv.includes('--check') ? 'check' : 'generation'} PASS: ${abi.length} entries; frozen interface matches`)
